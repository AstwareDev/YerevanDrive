import { NodeIO } from '@gltf-transform/core';
import { ALL_EXTENSIONS } from '@gltf-transform/extensions';
import { MeshoptDecoder } from 'meshoptimizer';
await MeshoptDecoder.ready;
const io = new NodeIO().registerExtensions(ALL_EXTENSIONS).registerDependencies({ 'meshopt.decoder': MeshoptDecoder });
const doc = await io.read(process.argv[2]), root = doc.getRoot();
const names = []; const walk = (n, d) => { const m = n.getMesh(); let t = 0; if (m) for (const p of m.listPrimitives()) t += (p.getIndices()?.getCount() ?? 0) / 3; names.push({ d, n: n.getName(), t: Math.round(t), tr: n.getTranslation().map(v => +v.toFixed(3)), s: n.getScale().map(v => +v.toFixed(3)), kids: n.listChildren().length }); n.listChildren().forEach(c => walk(c, d + 1)); };
root.listScenes()[0].listChildren().forEach(n => walk(n, 0));
console.log('total nodes', names.length);
for (const x of names) if (/wheel|tire|tyre|rim|brake|callip|joint|group|disc|steer/i.test(x.n)) console.log(' '.repeat(x.d) + x.n.slice(0, 90), x.t + 't', 'T' + x.tr, 'S' + x.s);
const sk = root.listSkins()[0]; console.log('skin joints', sk.listJoints().length, sk.listJoints().slice(0, 12).map(j => j.getName()));
